// Generate the user profile counterpart from the character's tested layout.
// No generation or stylesheet parsing happens in the running extension.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), css = path.join(root, 'css');
const map = text => text.replaceAll('salty-profile-', 'salty-user-profile-')
    .replaceAll(':not([is_user="true"])', '[is_user="true"]')
    .replaceAll('--bl-profile-', '--bl-user-profile-').replaceAll('--bl-name-', '--bl-user-name-')
    .replaceAll('--bl-meta-', '--bl-user-meta-').replaceAll('--bl-header-', '--bl-user-header-')
    .replaceAll('--bl-button-', '--bl-user-button-').replaceAll('--salty-font-name', '--salty-font-userName').replaceAll('--bl-art-shadow-profile', '--bl-art-shadow-userProfile');
let generated = map(fs.readFileSync(path.join(css, '40-profile.css'), 'utf8')) + '\n' + map(fs.readFileSync(path.join(css, '42-profile-name.css'), 'utf8'));
const decor = fs.readFileSync(path.join(css, '41-decor.css'), 'utf8');
const binding = decor.match(/\.bl-art-frame\[data-bl-frame="profile"\] \{[\s\S]*?\}/)[0];
generated += '\n' + map(binding).replace('data-bl-frame="profile"', 'data-bl-frame="userProfile"');
for (const match of decor.matchAll(/body\.salty\.salty-profile[^{}]+\{[^{}]*\}/g)) generated += '\n' + map(match[0]);
const user = 'body.salty.salty-user-profile-mode-small #chat .mes[is_user="true"]:not([is_system="true"]):not(.smallSysMes)';
generated += `
${user} { display: grid !important; grid-template-columns: 34px 12px auto auto auto minmax(0, 1fr) !important; grid-template-rows: auto auto !important; }
${user} > .mesAvatarWrapper { display: contents !important; }
${user} > .mesAvatarWrapper > .avatar { grid-area: 2 / 1 !important; }
${user} > .mes_block { grid-area: 2 / 3 / 3 / -1 !important; width: 100% !important; padding-inline: 0 !important; }
${user} > .mesAvatarWrapper > .mesIDDisplay { grid-area: 1 / 3 !important; }
${user} > .mesAvatarWrapper > .mes_timer { grid-area: 1 / 4 !important; }
${user} > .mesAvatarWrapper > .tokenCounterDisplay { grid-area: 1 / 5 !important; }
${user} > :is(.for_checkbox, .del_checkbox) { grid-area: 1 / 1 !important; }
`;
const right = user.replace('body.salty.', 'body.salty.salty-user-profile-side-right.');
generated += `
${right} { grid-template-columns: auto auto auto minmax(0, 1fr) 12px 34px !important; }
${right} > .mesAvatarWrapper > .avatar { grid-area: 2 / 6 !important; }
${right} > .mes_block { grid-area: 2 / 1 / 3 / 5 !important; }
${right} > .mesAvatarWrapper > .mesIDDisplay { grid-area: 1 / 1 !important; }
${right} > .mesAvatarWrapper > .mes_timer { grid-area: 1 / 2 !important; }
${right} > .mesAvatarWrapper > .tokenCounterDisplay { grid-area: 1 / 3 !important; }
${right} > :is(.for_checkbox, .del_checkbox) { grid-area: 1 / 6 !important; }
`;
// 4.3.4 번호 · 시간 · 토큰 줄을 오른쪽 끝에 (내 프로필 › '번호 · 시간 줄 위치'). 사진이 왼쪽이든 오른쪽이든 남는 칸을 앞에 두고 세 칸을 뒤로 민다
const metaRight = user.replace('body.salty.', 'body.salty.salty-user-meta-right.');
const metaRightSide = right.replace('body.salty.', 'body.salty.salty-user-meta-right.');
generated += `
${metaRight} { grid-template-columns: 34px 12px minmax(0, 1fr) auto auto auto !important; }
${metaRight} > .mesAvatarWrapper > .mesIDDisplay { grid-area: 1 / 4 !important; }
${metaRight} > .mesAvatarWrapper > .mes_timer { grid-area: 1 / 5 !important; }
${metaRight} > .mesAvatarWrapper > .tokenCounterDisplay { grid-area: 1 / 6 !important; }
${metaRightSide} { grid-template-columns: minmax(0, 1fr) auto auto auto 12px 34px !important; }
${metaRightSide} > .mes_block { grid-area: 2 / 1 / 3 / 5 !important; }
${metaRightSide} > .mesAvatarWrapper > .mesIDDisplay { grid-area: 1 / 2 !important; }
${metaRightSide} > .mesAvatarWrapper > .mes_timer { grid-area: 1 / 3 !important; }
${metaRightSide} > .mesAvatarWrapper > .tokenCounterDisplay { grid-area: 1 / 4 !important; }
`;
generated += `
body.salty:is(.salty-user-bubble, .salty-user-card).salty-user-profile-custom #chat .mes[is_user="true"]:not([is_system="true"]):not(.smallSysMes) > .mes_block { padding: 12px 16px 14px !important; }
body.salty:is(.salty-user-bubble, .salty-user-card).salty-user-profile-mode-none #chat .mes[is_user="true"]:not([is_system="true"]) > .mes_block { padding-left: 16px !important; }
body.salty.salty-user-card.salty-user-profile-mode-none #chat .mes[is_user="true"]:not([is_system="true"]):not(.smallSysMes) { --salty-meta-inset: 16px; }
body.salty.salty-user-card.salty-user-profile-mode-none #chat .mes[is_user="true"]:not([is_system="true"]):not(.smallSysMes) > .mes_block { margin-left: 0 !important; }
`;
fs.writeFileSync(path.join(css, '43-user-profile.gen.css'), '/* ===== css/43-user-profile.gen.css ===== */\n/* Generated by tools/gen-user-profile.cjs. */\n' + generated);
console.log('Generated user profile CSS');
