import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const root=pathToFileURL(path.resolve(process.argv[2]||'.')+'/');
const {getSettings,DEFAULTS}=await import(new URL('src/settings.js',root));
const {addonMarkup}=await import(new URL('src/addons.js',root));
const {settingRoute}=await import(new URL('src/settings-differences.js',root));
const {IDS}=await import(new URL('src/assist/core.js',root));
const saved={enabled:true,addons:{models:true,modelswitch:true,regexlink:true,conflicts:true,zipinstall:true},addonUI:{modelswitchMenu:false,zipinstallMenu:false}};
globalThis.SillyTavern={getContext:()=>({extensionSettings:{salty:saved}})};
const s=getSettings();
assert.deepEqual(IDS,['conflicts']);
assert.equal(s.addonUI.modelswitchMenu,false);
for(const id of ['models','modelswitch','regexlink','conflicts'])assert.equal(s.addons[id],true);
assert.equal(DEFAULTS.addonUI.modelswitchMenu,true);
assert.equal(DEFAULTS.addonUI.zipinstallMenu,true);assert.equal(s.addonUI.zipinstallMenu,false);
const zip=addonMarkup(s,'zipinstall');assert.match(zip,/data-addon-menu="zipinstall"/);assert.match(zip,/ZIP 설치 숨김/);assert.doesNotMatch(zip,/data-addon-menu="zipinstall" checked/);
s.addonUI.zipinstallMenu=true;const zipOn=addonMarkup(s,'zipinstall');s.addonUI.zipinstallMenu=false;assert.match(zipOn,/data-addon-menu="zipinstall" checked/);assert.match(zipOn,/fa-file-zipper/);assert.doesNotMatch(zipOn,/ZIP 설치 숨김/);
const models=addonMarkup(s,'models'),perf=addonMarkup(s,'perf');
assert.match(models,/모델 관리/);assert.match(models,/data-addon-toggle="models"/);assert.match(models,/data-addon-toggle="modelswitch"/);assert.match(models,/모델 전환 숨김/);
assert.match(perf,/data-addon-toggle="regexlink"/);assert.match(perf,/data-assist-toggle="conflicts"/);
assert.doesNotMatch(models+perf,/data-assist-toggle="(?:taste|requestview)"/);
for(const key of ['modelswitch','modelorder'])assert.equal(settingRoute('addons.'+key).sub,'models');
for(const key of ['regexlink','conflicts'])assert.equal(settingRoute('addons.'+key).sub,'perf');
assert.equal(settingRoute('addonUI.modelswitchMenu').sub,'models');
assert.equal(settingRoute('addonUI.zipinstallMenu').sub,'zipinstall');
const {SETTING_LABELS}=await import(new URL('src/settings-labels.js',root));assert.equal(SETTING_LABELS['addonUI.zipinstallMenu'],'요술봉에 ZIP 설치 표시');
console.log('PASS grouped tools, legacy settings, menu preference and setting routes');
