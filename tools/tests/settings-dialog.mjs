import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(process.argv[2]||path.join(path.dirname(fileURLToPath(import.meta.url)),'../..'));
const source=fs.readFileSync(path.join(root,'src/settings-dialog.js'),'utf8').replaceAll('export function ','function ');
const context=vm.createContext({});vm.runInContext(source+';globalThis.api={bindSettingsDialog,leaveSettingsDialog}',context);
const {bindSettingsDialog,leaveSettingsDialog}=context.api;
const panel={},button={closest:()=>panel},calls=[],binding=bindSettingsDialog(panel);
let finished=false,finishClose;
const closed=new Promise(resolve=>finishClose=resolve);
const early=leaveSettingsDialog(button);early.then(()=>finished=true);
const duplicate=leaveSettingsDialog(button);assert.equal(duplicate,early,'repeated early clicks share one close request');
await new Promise(setImmediate);assert.equal(finished,false);assert.deepEqual(calls,[]);
binding.opened({completeAffirmative:()=>{calls.push('close');return closed}});
await new Promise(setImmediate);assert.deepEqual(calls,['close']);assert.equal(finished,false,'the next panel waits for the native close animation');
finishClose(1);assert.equal(await early,1);assert.equal(finished,true);binding.closed();
const cancelledPanel={},cancelledBinding=bindSettingsDialog(cancelledPanel);
const cancelled=leaveSettingsDialog({closest:()=>cancelledPanel});cancelledBinding.closed();assert.equal(await cancelled,false,'closing before onOpen cancels the pending shortcut');
const openPanel={},openBinding=bindSettingsDialog(openPanel);openBinding.opened({completeAffirmative:async()=>2});assert.equal(await leaveSettingsDialog({closest:()=>openPanel}),2);
assert.equal(leaveSettingsDialog({closest:()=>null}),undefined,'drawer settings remain mounted');
assert.equal(leaveSettingsDialog(null),undefined);
console.log('settings-dialog: early click, duplicate click, close animation, cancelled opening, ready popup and drawer passed');
